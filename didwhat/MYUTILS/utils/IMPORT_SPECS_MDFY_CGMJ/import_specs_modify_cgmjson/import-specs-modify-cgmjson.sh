#!/bin/bash

set -e

function clean_up {
    echo "====== Cleaning up ======"

    if [[ -d "$DOWNLOAD_DIR" ]]
    then
        rm -rf "$DOWNLOAD_DIR"
    fi
}
trap clean_up EXIT SIGINT SIGTERM

print_the_pkgname_part_from_srpm_filename_path() {
	local srpm_file=$1

	fnmpart=$(echo $srpm_file | sed -e "s/.*\///")
	fnm_ext_removed=$(echo $fnmpart | sed -e "s/\(.*\)\.src\.rpm/\1/")

	#print the name part of the package from file name
	#which requires us to print all the parts of the file name except for the
	#last two parts, where the parts have been derived using hyphen ("-") as 
	#the field separator
	echo $fnm_ext_removed | awk '
		BEGIN {FS = "-"} 
		NF < 3 {printf $0} 
		NF >= 3 { 
			for (i = 1; i <= NF - 2; i++)
			{ 
				if (i > 1) 
				{
					printf "-"
				} 
				printf $i; 
			}
		}'
}

print_the_pkgver_part_from_srpm_filename_path() {
	local srpm_file=$1

	fnmpart=$(echo $srpm_file | sed -e "s/.*\///")
	fnm_ext_removed=$(echo $fnmpart | sed -e "s/\(.*\)\.src\.rpm/\1/")

	#print the version part of the package from file name
	#which requires us to print the second last part of the file name, where
	#the parts have been derived using hyphen ("-") as the field separator
	echo $fnm_ext_removed | awk '
		BEGIN {FS = "-"} 
		NF < 3 {printf $0} 
		NF >= 3 {print $(NF - 1)}
		'
}

update_cgmanifest() {
    local import_srpm_dir=$1
    local cgmjson_fl=$2
    local srpms

    WORKING_CGM_FILE="$(mktemp -q)"

    srpms=$(find "$import_srpm_dir" -type f -name '*.src.rpm')$
    for srpm_file in $srpms; do
        echo $srpm_file
	pkgnm=$(print_the_pkgname_part_from_srpm_filename_path $srpm_file)
	echo $pkgnm

	pkgver=$(print_the_pkgver_part_from_srpm_filename_path $srpm_file)
	echo $pkgver

	#Carry out the substitution of the version field in the manifest json file for the given package
	awk -v awkvar_pkgnm="$pkgnm" -v awkvar_pkgver="$pkgver" -v awkvar_nmregex="\"name\": \"$pkgnm\"" -v awkvar_verregex="\"version\":" '
	BEGIN { changeverflag = 0 }
	# The line containing the name of the package must be printed as is, and lead to a flag set that ensures that
	# the next version line is changed, because that is the version line corresponding to this package
	$0 ~ awkvar_nmregex { changeverflag = 1
				print $0 
			}
	# The version line must have the determined version mentioned in it if it corresponds to the given package, i.e. the changeverflag is set
	# Any other version line must be printed as is
	$0 ~ awkvar_verregex {
			if (changeverflag == 1)
			{
				printf ("          \"version\": \"%s\",\n", awkvar_pkgver)
				changeverflag = 0
			}
			else
			{
				print $0
			}
		}
	# All the lines except for the ones that match the above criteria, must be printed unchanged.
	        {
	                if (! ($0 ~ awkvar_nmregex) && !($0 ~ awkvar_verregex) )
			{
				print $0
			}
		}
	' $cgmjson_fl > $WORKING_CGM_FILE
	
	cp $WORKING_CGM_FILE $cgmjson_fl
	
	done


}

expand_srpms() {
