print_usage() {
    echo "Usage:"
    echo "import-specs.sh [distro] [package list file] [cgmanigest json file] [directory path if srpms to be retained]"
    echo
    echo "Supported distros: fedora, centos, opensuse"
    echo
    echo "Example for not retaining srpms"
    echo "import-specs.sh fedora /path/to/packagelist.txt cgmanifest.json"
    echo "or"
    echo "Example for retaining srpms"
    echo "import-specs.sh fedora /path/to/packagelist.txt cgmanifest.json dir_to_retain_srpms"
    echo "Caution: the cgmanifest json file provided as input is overwritten by the contents generated by this script"
    exit
}

if [ $# -lt 3 ]; then
    print_usage
fi

DISTRO=$1
PACKAGE_LIST=$2
CGM_JSON_FILE=$3

if [ $# -eq 4 ]
then
retain_srpm_flag=1
RETAIN_SRPM_DIR=$4
else
retain_srpm_flag=0
fi

SCRIPT_DIR="$(cd "$( dirname "${BASH_SOURCE[0]}" )" >/dev/null 2>&1 && pwd)"
OUTPUT_DIR="$SCRIPT_DIR/output/$DISTRO"
LOGS_DIR="$OUTPUT_DIR/logs"
SPECS_DIR="$OUTPUT_DIR/specs"
IMAGE_TAG="$DISTRO-srpm-importer"

DOWNLOAD_DIR="$(mktemp -d)"

mkdir -p "$LOGS_DIR"
mkdir -p "$SPECS_DIR"


cp "$PACKAGE_LIST" "$DOWNLOAD_DIR/packagelist.txt"

echo "====== Preparing Docker image ======"
docker build -t "$IMAGE_TAG" -f "$SCRIPT_DIR/container/$DISTRO.Dockerfile" "$SCRIPT_DIR/container"

echo "====== Retrieving source RPMs ======"
docker run -v "$DOWNLOAD_DIR":/srpms --rm "$IMAGE_TAG"

if [ $retain_srpm_flag -eq 1 ]
then
cp -r $DOWNLOAD_DIR $RETAIN_SRPM_DIR
fi

echo "====== Updating cgmanifest file provided ======"
update_cgmanifest "$DOWNLOAD_DIR" "$CGM_JSON_FILE"

echo "cgmanifest file updated"

echo "====== Expanding retrieved source RPMs ======"
expand_srpms "$DOWNLOAD_DIR" "$SPECS_DIR" "$LOGS_DIR"

echo "SPECs written to $SPECS_DIR"
